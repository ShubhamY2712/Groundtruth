// Generates lib/data/india-map.ts: a projected SVG outline of India plus pixel positions for each city.
//
// Outline: Survey of India boundary from the DataMeet India community
// (https://github.com/datameet/maps, CC BY 4.0), simplified once with:
//   npx mapshaper india-soi.geojson -dissolve -explode -filter 'this.area > 3e8' \
//     -simplify 1.2% keep-shapes -o format=geojson precision=0.001 scripts/data/india.geojson
//
// Run: npm run build:map
import { readFileSync, writeFileSync } from "node:fs";
import { geoMercator, geoPath } from "d3-geo";

const WIDTH = 560;
const HEIGHT = 640;

const outline = JSON.parse(readFileSync(new URL("./data/india.geojson", import.meta.url)));
const coords = JSON.parse(readFileSync(new URL("../lib/data/city-coords.json", import.meta.url)));

// mapshaper writes RFC 7946 winding (counter-clockwise exteriors); d3-geo expects clockwise, so reverse rings.
const rewind = (g) => ({ ...g, coordinates: g.coordinates.map((ring) => [...ring].reverse()) });
const feature = {
  type: "FeatureCollection",
  features: outline.geometries.map((g) => ({ type: "Feature", properties: {}, geometry: rewind(g) })),
};

const projection = geoMercator().fitExtent(
  [
    [12, 12],
    [WIDTH - 12, HEIGHT - 12],
  ],
  feature,
);
const path = geoPath(projection);
const d = feature.features.map((f) => path(f)).join("");
const round = (n) => Math.round(n * 10) / 10;
const points = Object.fromEntries(
  Object.entries(coords).map(([id, c]) => {
    const [x, y] = projection([c.lng, c.lat]);
    return [id, { x: round(x), y: round(y), label: c.label }];
  }),
);

const out = `// Generated by scripts/build-map.mjs. Do not edit by hand.
// Boundary: Survey of India outline via DataMeet India community (CC BY 4.0).
export const INDIA_MAP = {
  width: ${WIDTH},
  height: ${HEIGHT},
  path: ${JSON.stringify(d.replace(/(\d+\.\d)\d+/g, "$1"))},
  points: ${JSON.stringify(points, null, 2)} as Record<string, { x: number; y: number; label: "left" | "right" }>,
} as const;
`;
writeFileSync(new URL("../lib/data/india-map.ts", import.meta.url), out);
console.log(`Wrote lib/data/india-map.ts (${out.length} bytes, ${Object.keys(points).length} cities)`);
